"""CPU-only calibration of the RF-camera angular FFT.

The first MVP intentionally saved the direct NumPy FFT of the receive-aperture
matrix. That is useful for validating Sionna array extraction, but two details
must be corrected before interpreting the complex spectrum as a physical
angular field:

1. Sionna's PlanarArray rows run from +z to -z, so the FFT row coordinate has
   the opposite sign of physical local kz/k.
2. The physical aperture is centered on the UE, while ``np.fft.fft2`` treats
   matrix index (0, 0) as the spatial origin. This does not change power, but it
   adds a deterministic linear phase ramp to the angular spectrum.

This module performs those two calibrations without re-running path tracing.
"""

from __future__ import annotations

import argparse
import json
from dataclasses import dataclass
from pathlib import Path

import numpy as np


@dataclass(frozen=True)
class AngularCalibration:
    """A physically oriented angular field and its local direction axes."""

    cfr: np.ndarray
    ky_over_k: np.ndarray
    kz_over_k: np.ndarray


def calibrate_angular_cfr(
    raw_angular_cfr: np.ndarray,
    *,
    aperture_rows: int,
    aperture_cols: int,
    horizontal_spacing_lambda: float,
    vertical_spacing_lambda: float,
) -> AngularCalibration:
    """Convert the raw matrix FFT into a UE-local physical angular field.

    The input is the direct ``fftshift(fft2(aperture))`` generated by the MVP.
    The returned array has shape ``[kz, ky, frequency]`` with both coordinate
    arrays increasing in the physical local +z and +y directions.

    The phase correction follows directly from the centered PlanarArray
    positions

    ``y_j = d_h (j - (C-1)/2)``
    ``z_i = d_v ((R-1)/2 - i)``.

    It therefore preserves the complex phase that would be obtained by a
    Fourier sum using the actual centered antenna positions.
    """
    raw = np.asarray(raw_angular_cfr)
    if raw.ndim != 3:
        raise ValueError("raw_angular_cfr must have shape [fft_row, fft_col, frequency]")
    if aperture_rows < 1 or aperture_cols < 1:
        raise ValueError("aperture_rows and aperture_cols must be >= 1")
    if horizontal_spacing_lambda <= 0 or vertical_spacing_lambda <= 0:
        raise ValueError("antenna spacing must be > 0")

    fft_rows, fft_cols, _ = raw.shape
    q_row = np.fft.fftshift(np.fft.fftfreq(fft_rows))
    q_col = np.fft.fftshift(np.fft.fftfreq(fft_cols))

    # np.fft assumes sample positions i,j starting at zero. The actual Sionna
    # aperture is centered, so restore the phase origin to the UE center.
    phase_origin = np.exp(
        1j
        * 2.0
        * np.pi
        * (
            q_row[:, None] * (aperture_rows - 1) / 2.0
            + q_col[None, :] * (aperture_cols - 1) / 2.0
        )
    )
    centered = raw * phase_origin[:, :, None]

    # PlanarArray row index increases toward local -z. Flip the FFT row axis so
    # the returned image increases toward physical local +z.
    calibrated = np.flip(centered, axis=0).copy()

    ky_over_k = q_col / horizontal_spacing_lambda
    kz_over_k = -q_row[::-1] / vertical_spacing_lambda

    return AngularCalibration(
        cfr=calibrated,
        ky_over_k=ky_over_k,
        kz_over_k=kz_over_k,
    )


def rotation_matrix_numpy(orientation: tuple[float, float, float]) -> np.ndarray:
    """Return Sionna's (z, y, x) device rotation matrix as a NumPy array."""
    alpha, beta, gamma = orientation
    sa, ca = np.sin(alpha), np.cos(alpha)
    sb, cb = np.sin(beta), np.cos(beta)
    sg, cg = np.sin(gamma), np.cos(gamma)

    return np.array(
        [
            [ca * cb, ca * sb * sg - sa * cg, ca * sb * cg + sa * sg],
            [sa * cb, sa * sb * sg + ca * cg, sa * sb * cg - ca * sg],
            [-sb, cb * sg, cb * cg],
        ],
        dtype=np.float64,
    )


def geometric_los_source_direction_local(
    *,
    tx_position: tuple[float, float, float],
    ue_position: tuple[float, float, float],
    ue_orientation: tuple[float, float, float],
) -> np.ndarray:
    """Return the UE-local unit vector pointing from the UE toward the BS.

    Sionna's receive-array synthetic phase uses the arrival/source direction.
    The 2-D planar aperture observes only its local y-z projection; the sign of
    local x remains a front/back ambiguity for phase-only planar sampling.
    """
    tx = np.asarray(tx_position, dtype=np.float64)
    ue = np.asarray(ue_position, dtype=np.float64)
    world = tx - ue
    distance = float(np.linalg.norm(world))
    if distance == 0.0:
        raise ValueError("Tx and UE positions must differ")
    world /= distance

    rotation = rotation_matrix_numpy(ue_orientation)
    local = rotation.T @ world
    return local / np.linalg.norm(local)


def angular_peak_projection(
    angular_slice: np.ndarray,
    *,
    ky_over_k: np.ndarray,
    kz_over_k: np.ndarray,
) -> tuple[float, float, tuple[int, int]]:
    """Return the strongest angular bin as (ky/k, kz/k, (row, col))."""
    power = np.abs(np.asarray(angular_slice)) ** 2
    row, col = np.unravel_index(int(np.argmax(power)), power.shape)
    return float(ky_over_k[col]), float(kz_over_k[row]), (int(row), int(col))


def calibrate_directory(output_dir: Path, phase_floor_db: float = -35.0) -> dict[str, Path]:
    """Calibrate one existing RF-camera output directory and render diagnostics."""
    output_dir = Path(output_dir)
    raw_path = output_dir / "angular_cfr.npy"
    metadata_path = output_dir / "rf_camera_metadata.json"
    if not raw_path.exists():
        raise FileNotFoundError(raw_path)
    if not metadata_path.exists():
        raise FileNotFoundError(metadata_path)

    raw = np.load(raw_path)
    metadata = json.loads(metadata_path.read_text(encoding="utf-8"))
    cfg = metadata["config"]

    calibration = calibrate_angular_cfr(
        raw,
        aperture_rows=int(cfg["rx_rows"]),
        aperture_cols=int(cfg["rx_cols"]),
        horizontal_spacing_lambda=float(cfg["horizontal_spacing_lambda"]),
        vertical_spacing_lambda=float(cfg["vertical_spacing_lambda"]),
    )

    calibrated_path = output_dir / "angular_cfr_calibrated.npy"
    np.save(calibrated_path, calibration.cfr.astype(np.complex64, copy=False))

    center_bin = calibration.cfr.shape[2] // 2
    angular_slice = calibration.cfr[:, :, center_bin]
    peak_ky, peak_kz, peak_index = angular_peak_projection(
        angular_slice,
        ky_over_k=calibration.ky_over_k,
        kz_over_k=calibration.kz_over_k,
    )

    los_local = geometric_los_source_direction_local(
        tx_position=tuple(cfg["tx_position"]),
        ue_position=tuple(cfg["ue_position"]),
        ue_orientation=tuple(cfg["ue_orientation"]),
    )
    los_ky = float(los_local[1])
    los_kz = float(los_local[2])
    los_projection_error = float(np.hypot(peak_ky - los_ky, peak_kz - los_kz))

    print("=== RF Camera angular calibration ===")
    print(
        "geometric LoS source direction, UE-local: "
        f"kx/k={los_local[0]:+.6f}, ky/k={los_ky:+.6f}, kz/k={los_kz:+.6f}"
    )
    print(
        "center-bin angular peak: "
        f"ky/k={peak_ky:+.6f}, kz/k={peak_kz:+.6f}, index={peak_index}"
    )
    print(f"peak-to-LoS yz projection error={los_projection_error:.6f}")
    print(
        "note: a planar y-z aperture has front/back ambiguity in local x; "
        "the angular image alone does not determine the sign of kx/k"
    )

    power = np.abs(angular_slice) ** 2
    peak_power = max(float(np.max(power)), 1e-30)
    power_db = 10.0 * np.log10(np.maximum(power / peak_power, 1e-12))
    phase = np.angle(angular_slice)
    phase_masked = np.ma.masked_where(power_db < phase_floor_db, phase)

    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    extent = [
        float(calibration.ky_over_k[0]),
        float(calibration.ky_over_k[-1]),
        float(calibration.kz_over_k[0]),
        float(calibration.kz_over_k[-1]),
    ]

    power_png = output_dir / "angular_power_center_calibrated.png"
    fig, ax = plt.subplots(figsize=(8, 6))
    image = ax.imshow(
        power_db,
        origin="lower",
        extent=extent,
        aspect="auto",
        vmin=-60.0,
        vmax=0.0,
    )
    ax.scatter([los_ky], [los_kz], marker="x", label="geometric LoS")
    ax.scatter([peak_ky], [peak_kz], marker="+", label="strongest bin")
    ax.set_xlabel("UE-local horizontal direction cosine ky/k")
    ax.set_ylabel("UE-local vertical direction cosine kz/k")
    ax.set_title("RF camera angular spectrum: calibrated normalized power [dB]")
    ax.legend()
    fig.colorbar(image, ax=ax, label="dB relative to peak")
    fig.tight_layout()
    fig.savefig(power_png, dpi=150)
    plt.close(fig)

    phase_png = output_dir / "angular_phase_center_calibrated.png"
    fig, ax = plt.subplots(figsize=(8, 6))
    image = ax.imshow(
        phase_masked,
        origin="lower",
        extent=extent,
        aspect="auto",
        vmin=-np.pi,
        vmax=np.pi,
    )
    ax.scatter([los_ky], [los_kz], marker="x", label="geometric LoS")
    ax.set_xlabel("UE-local horizontal direction cosine ky/k")
    ax.set_ylabel("UE-local vertical direction cosine kz/k")
    ax.set_title(
        "RF camera angular spectrum: calibrated phase [rad] "
        f"(power >= {phase_floor_db:g} dB)"
    )
    ax.legend()
    fig.colorbar(image, ax=ax, label="phase [rad]")
    fig.tight_layout()
    fig.savefig(phase_png, dpi=150)
    plt.close(fig)

    report_path = output_dir / "angular_calibration.json"
    report = {
        "schema_version": 1,
        "source_angular_cfr": raw_path.name,
        "calibrated_angular_cfr": calibrated_path.name,
        "coordinate_convention": {
            "array_plane": "UE-local y-z",
            "horizontal_axis": "local ky/k, increasing toward +y",
            "vertical_axis": "local kz/k, increasing toward +z",
            "array_normal": "local x",
            "front_back_ambiguity": "planar phase sampling does not determine sign of local kx/k",
        },
        "phase_origin": "UE/aperture center",
        "geometric_los_source_direction_local": {
            "kx_over_k": float(los_local[0]),
            "ky_over_k": los_ky,
            "kz_over_k": los_kz,
        },
        "center_frequency_peak": {
            "ky_over_k": peak_ky,
            "kz_over_k": peak_kz,
            "index": list(peak_index),
            "yz_projection_error_to_geometric_los": los_projection_error,
        },
        "phase_plot_power_floor_db": float(phase_floor_db),
    }
    report_path.write_text(json.dumps(report, indent=2), encoding="utf-8")

    print(f"calibrated CFR: {calibrated_path}")
    print(f"calibrated power: {power_png}")
    print(f"calibrated phase: {phase_png}")
    print(f"calibration report: {report_path}")

    return {
        "calibrated_cfr": calibrated_path,
        "power_png": power_png,
        "phase_png": phase_png,
        "report": report_path,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description="Calibrate an RF-camera MVP angular FFT")
    parser.add_argument("output_dir", type=Path, help="Existing rf_camera output directory")
    parser.add_argument(
        "--phase-floor-db",
        type=float,
        default=-35.0,
        help="Mask phase below this power level relative to the peak",
    )
    args = parser.parse_args()
    calibrate_directory(args.output_dir, phase_floor_db=args.phase_floor_db)


if __name__ == "__main__":
    main()
